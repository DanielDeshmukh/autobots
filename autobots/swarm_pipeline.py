# -- Pipeline ---------------------------------------------------------------

def run_pipeline(goal, output_dir, max_healing_rounds=3):
    """Main pipeline: plan -> execute -> verify -> heal -> repeat until success."""
    project_path = Path(output_dir)
    project_path.mkdir(parents=True, exist_ok=True)

    logger.info(f"\n{'='*60}")
    logger.info(f"SWARM PIPELINE -- Self-Healing Mode")
    logger.info(f"{'='*60}")
    logger.info(f"Goal: {goal}")
    logger.info(f"Output: {project_path}")
    logger.info(f"Log: {log_file}")
    logger.info(f"Max healing rounds: {max_healing_rounds}")

    rate_limiter = RateLimiter(max_per_minute=35, min_interval=2.0)
    all_files = []
    all_tasks = []
    build_ok = False
    tasks = []
    last_build_error = ""
    same_error_count = 0

    for healing_round in range(max_healing_rounds + 1):
        if healing_round == 0:
            logger.info(f"\n{'='*60}")
            logger.info(f"ROUND 1: INITIAL PLANNING")
            logger.info(f"{'='*60}")
            tasks, type_contracts, architecture = plan_tasks(goal, rate_limiter)
            if not tasks:
                logger.error("No tasks planned. Aborting.")
                return []
        else:
            logger.info(f"\n{'='*60}")
            logger.info(f"HEALING ROUND {healing_round}: REMEDIATION")
            logger.info(f"{'='*60}")

            # If tasks were set by build-fix from previous round, use them directly
            if not tasks:
                missing, empty = verify_files(project_path, all_tasks)
                logic_issues = verify_logic(project_path)
                failed_tasks = [t for t in all_tasks if t.status == "failed"]

                if not missing and not empty and not logic_issues and not failed_tasks:
                    logger.info("[HEALING] All checks passed, no healing needed")
                    break

                tasks = plan_remediation(goal, failed_tasks, missing, logic_issues, all_tasks, rate_limiter, project_path)
                if not tasks:
                    logger.warning("[HEALING] No remediation tasks generated")
                    break

            type_contracts = ""
            architecture = ""

        # Build shared context with import paths
        tasks_list = "\n".join([
            f"- {t.task_id} [{t.cluster}] {t.description}" for t in tasks
        ])
        
        # Build import map from task dependencies
        import_map = []
        for t in tasks:
            if t.depends_on:
                for dep_id in t.depends_on:
                    dep_task = next((x for x in tasks if x.task_id == dep_id), None)
                    if dep_task:
                        import_map.append(f"- {t.task_id} imports from {dep_id}: {dep_task.files[0] if dep_task.files else 'unknown'}")
        
        import_map_str = "\n".join(import_map) if import_map else "No cross-task imports"
        
        shared_context = f"""Project: {goal}

Architecture: {architecture}

Tasks:
{tasks_list}

IMPORT MAP (workers must use these exact paths):
{import_map_str}

TYPE CONTRACTS:
{type_contracts}

DESIGN RULES:
- Colors: cohesive palette (blues #3b82f6/#60a5fa/#1e40af)
- Shadows: 0 4px 6px -1px rgba(0,0,0,0.1)
- Transitions: all 0.2s ease
- Typography: font-weight 600-700 headings
- Spacing: 16-24px padding
- Border-radius: 8-12px cards, 6px buttons
- Dark: #0f172a, #1e293b, #334155
- Light: #f8fafc, #f1f5f9, #e2e8f0"""

        (project_path / "SHARED_CONTEXT.md").write_text(shared_context, encoding="utf-8")

        # Write critical boilerplate files first
        critical_written = write_critical_files(project_path)
        if critical_written:
            logger.info(f"[CRITICAL] Created {critical_written} boilerplate files")

        # Execute tasks
        logger.info(f"\n[EXEC] Running {len(tasks)} tasks...")
        write_lock = threading.Lock()
        max_concurrent = 2
        semaphore = threading.Semaphore(max_concurrent)

        def run_task(t):
            with semaphore:
                files = execute_task(t, shared_context, rate_limiter, project_path)
                if files:
                    # Code review gate before writing
                    reviewed_files = review_code(t, files, shared_context, rate_limiter)
                    if reviewed_files:
                        # Output guardrail before writing
                        validated_files = validate_output(t, reviewed_files, rate_limiter)
                        if validated_files:
                            with write_lock:
                                all_files.extend(validated_files)
                                for f in validated_files:
                                    path = f.get("path", "")
                                    content = f.get("content", "")
                                    if path and content:
                                        target = project_path / path
                                        target.parent.mkdir(parents=True, exist_ok=True)
                                        target.write_text(content, encoding="utf-8")
                                        logger.info(f"  -> {path}")
                                # Create skill from successful task
                                create_skill_from_task(t, validated_files, project_path)

        wave = 0
        pending = [t for t in tasks if t.status == "pending"]
        while pending:
            ready = get_ready_tasks(tasks)
            if not ready:
                stuck = [t for t in tasks if t.status == "pending"]
                if stuck:
                    logger.warning(f"[DEPENDENCY] Stuck: {[t.task_id for t in stuck]} -- running anyway")
                    for t in stuck[:max_concurrent]:
                        t.depends_on = []
                else:
                    break

            wave += 1
            logger.info(f"\n[WAVE {wave}] Running {len(ready)} tasks: {[t.task_id for t in ready]}")

            threads = []
            for t in ready:
                t.status = "running"
                thread = threading.Thread(target=run_task, args=(t,))
                threads.append(thread)
                thread.start()

            for thread in threads:
                thread.join(timeout=300)

            pending = [t for t in tasks if t.status == "pending"]

        all_tasks.extend(tasks)
        tasks = []  # Reset so next round doesn't reuse

        # Always try install + build -- compiler errors give better signal than import checks
        install_ok, install_errors = install_deps(project_path)
        if not install_ok:
            logger.error("[INSTALL] Dependencies failed, feeding errors to planner")
            build_fix_tasks = plan_build_fix(goal, install_errors, rate_limiter, project_path)
            if build_fix_tasks:
                tasks = build_fix_tasks
                continue
            logger.error("[INSTALL] Planner could not generate fixes, giving up")
            break

        build_ok, build_errors = build_project(project_path)
        if build_ok:
            logger.info(f"\n{'='*60}")
            logger.info(f"BUILD SUCCEEDED -- PROJECT COMPLETE")
            logger.info(f"{'='*60}")
            break
        else:
            # Circuit breaker: if same error 3 times in a row, stop
            error_key = build_errors[:200]
            if error_key == last_build_error:
                same_error_count += 1
                if same_error_count >= 3:
                    logger.error(f"[BUILD] Same error {same_error_count} times in a row, stopping loop")
                    break
            else:
                same_error_count = 0
            last_build_error = error_key

            logger.error("[BUILD] Build failed, feeding errors to planner")
            build_fix_tasks = plan_build_fix(goal, build_errors, rate_limiter, project_path)
            if build_fix_tasks:
                tasks = build_fix_tasks
                continue
            logger.error("[BUILD] Planner could not generate fixes, giving up")
            break

    # Final summary
    logger.info(f"\n{'='*60}")
    logger.info(f"PIPELINE FINAL SUMMARY")
    logger.info(f"{'='*60}")

    done = [t for t in all_tasks if t.status == "done"]
    failed = [t for t in all_tasks if t.status == "failed"]
    missing, empty = verify_files(project_path, all_tasks)
    logic_issues = verify_logic(project_path)

    logger.info(f"Total tasks: {len(all_tasks)} ({len(done)} done, {len(failed)} failed)")
    logger.info(f"Total files: {len(all_files)} written")
    logger.info(f"Missing files: {len(missing)}")
    logger.info(f"Logic issues: {len(logic_issues)}")
    logger.info(f"Build: {'PASSED' if build_ok else 'FAILED'}")

    for t in all_tasks:
        status = "[OK]" if t.status == "done" else "[FAIL]" if t.status == "failed" else "[WAIT]"
        logger.info(f"  {status} {t.task_id} [{t.cluster}/{t.model_used}] {t.elapsed:.1f}s")

    summary = {
        "goal": goal,
        "timestamp": timestamp,
        "tasks_total": len(all_tasks),
        "tasks_done": len(done),
        "tasks_failed": len(failed),
        "files_written": len(all_files),
        "missing_files": [m["file"] for m in missing],
        "logic_issues": logic_issues,
        "build_passed": build_ok,
        "log_file": str(log_file),
    }
    (project_path / "swarm_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")

    return all_files


