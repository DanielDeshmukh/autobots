# -- Rate Limiter -----------------------------------------------------------

class RateLimiter:
    def __init__(self, max_per_minute=35, min_interval=2.0):
        self.max_per_minute = max_per_minute
        self.min_interval = min_interval
        self.calls = []
        self.lock = threading.Lock()

    def wait_if_needed(self):
        with self.lock:
            now = time.time()
            self.calls = [t for t in self.calls if now - t < 60]
            if self.calls:
                elapsed = now - self.calls[-1]
                if elapsed < self.min_interval:
                    time.sleep(self.min_interval - elapsed)
                    now = time.time()
                    self.calls = [t for t in self.calls if now - t < 60]
            if len(self.calls) >= self.max_per_minute:
                wait_time = 60 - (now - self.calls[0]) + 0.5
                logger.info(f"[rate-limit] Waiting {wait_time:.1f}s (limit reached)")
                time.sleep(wait_time)
                now = time.time()
                self.calls = [t for t in self.calls if now - t < 60]
            self.calls.append(time.time())

    def backoff(self):
        logger.info("[rate-limit] Backoff: waiting 30s")
        time.sleep(30)


# -- JSON Parser ------------------------------------------------------------

def parse_json_response(content, label=""):
    if not content:
        logger.debug(f"[json] Empty content for {label}")
        return None

    import re
    content = content.strip()

    # Remove markdown code fences
    if content.startswith("```json"):
        content = content[7:]
    if content.startswith("```"):
        content = content[3:]
    if content.endswith("```"):
        content = content[:-3]
    content = content.strip()

    # Try to find JSON object
    match = re.search(r"\{.*\}", content, re.DOTALL)
    if not match:
        # Try to find code blocks with TypeScript/JavaScript
        code_block = re.search(r"(?:typescript|javascript|ts|js)\s*\n(.*?)$", content, re.DOTALL)
        if code_block:
            code = code_block.group(1).strip()
            path_match = re.search(r"//\s*(src/\S+)", code)
            path = path_match.group(1) if path_match else "src/unknown.ts"
            return {"files": [{"path": path, "content": code}]}
        logger.debug(f"[json] No JSON found for {label}")
        return None

    raw = match.group()

    # Try direct parse
    try:
        return json.loads(raw, strict=False)
    except json.JSONDecodeError:
        pass

    # Try various fixes
    fixes = [
        lambda s: s.replace('\n', '\\n'),
        lambda s: s.replace('\r', ''),
        lambda s: s.replace('\t', '\\t'),
        lambda s: re.sub(r",\s*([}\]])", r"\1", s),
        lambda s: s.replace('\\\\n', '\\n'),
        lambda s: s.replace('\\"', '"'),
        lambda s: re.sub(r"\\/", "/", s),
        lambda s: re.sub(r"[\x00-\x1f]", " ", s),
    ]
    for fix in fixes:
        try:
            return json.loads(fix(raw))
        except json.JSONDecodeError:
            continue

    # Try to extract just the files array
    files_match = re.search(r'"files"\s*:\s*\[.*?\]', raw, re.DOTALL)
    if files_match:
        try:
            return json.loads("{" + files_match.group() + "}")
        except json.JSONDecodeError:
            pass

    # Try to extract items or tasks array
    items_match = re.search(r'"(?:items|tasks)"\s*:\s*\[.*?\]', raw, re.DOTALL)
    if items_match:
        try:
            return json.loads("{" + items_match.group() + "}")
        except json.JSONDecodeError:
            pass

    # Last resort: try to fix common JSON issues
    try:
        # Remove trailing commas
        fixed = re.sub(r",\s*([}\]])", r"\1", raw)
        # Fix unescaped newlines in strings
        fixed = re.sub(r'(?<=")[^"]*(?=")', lambda m: m.group().replace('\n', '\\n'), fixed)
        return json.loads(fixed)
    except json.JSONDecodeError:
        pass

    logger.debug(f"[json] All parse attempts failed for {label}")
    return None


# -- Task Dataclass ---------------------------------------------------------

@dataclass
class Task:
    task_id: str
    description: str
    files: list[str]
    cluster: str
    depends_on: list[str] = field(default_factory=list)
    priority: str = "medium"
    status: str = "pending"  # pending, running, done, failed
    model_used: str = ""
    elapsed: float = 0.0


def normalize_files(files):
    """Convert file specs to strings. Handles both 'path' strings and {'path':..., 'content':...} dicts."""
    result = []
    for f in files:
        if isinstance(f, dict):
            result.append(f.get("path", ""))
        else:
            result.append(str(f))
    return [f for f in result if f]


