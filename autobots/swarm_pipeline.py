def execute_task(task, shared_context, rate_limiter, project_path=None):
    """Execute a single task using its assigned cluster's model."""
    cluster_config = CLUSTERS.get(task.cluster)
    if not cluster_config or not cluster_config["system_prompt"]:
        logger.warning(f"[{task.task_id}] No prompt for cluster {task.cluster}, skipping")
        task.status = "failed"
        return []

    model_id = cluster_config["models"][0]
    model_name = model_id.split("/")[-1]

    logger.info(f"\n{'-'*60}")
    logger.info(f"[{task.task_id}] [cluster: {task.cluster} | model: {model_name}] working on: {task.description[:80]}")
    logger.info(f"  Files: {', '.join(task.files)}")

    task.status = "running"
    task.model_used = model_name

    client = OpenAI(
        base_url="https://integrate.api.nvidia.com/v1",
        api_key=os.environ.get("NVIDIA_API_KEY", ""),
    )

    # Load skills for this cluster
    file_extensions = [Path(f).suffix for f in task.files if f]
    cluster_skills = load_skills_for_cluster(task.cluster, file_extensions)
    project_skills = load_project_skills(project_path) if project_path else ""
    
    # Build enhanced system prompt with skills
    system = cluster_config["system_prompt"].format(
        files=", ".join(task.files),
        context=shared_context,
    )
    
    # Add skills to prompt
    if cluster_skills:
        system += f"\n\n{cluster_skills}"
    if project_skills:
        system += f"\n\n{project_skills}"

    try:
        rate_limiter.wait_if_needed()
        start = time.time()

        max_retries = 3
        for attempt in range(max_retries):
            try:
                r = client.chat.completions.create(
                    model=model_id,
                    messages=[{"role": "system", "content": system}, {"role": "user", "content": task.description}],
                    max_tokens=4096,
                    temperature=0.3,
                    timeout=120,
                )
                break
            except Exception as e:
                if ("429" in str(e) or "timed out" in str(e).lower() or "DEGRADED" in str(e)) and attempt < max_retries - 1:
                    logger.warning(f"[{task.task_id}] Retry {attempt + 1}: {type(e).__name__}")
                    rate_limiter.backoff()
                    continue
                raise

        elapsed = time.time() - start
        task.elapsed = elapsed
        content = r.choices[0].message.content or ""

        with open(LOG_DIR / f"task_{task.task_id}_{timestamp}.json", "w", encoding="utf-8") as f:
            json.dump({
                "task_id": task.task_id,
                "cluster": task.cluster,
                "model": model_id,
                "elapsed": elapsed,
                "content": content,
            }, f, indent=2, ensure_ascii=False)

        data = parse_json_response(content, task.task_id)
        if data and "files" in data:
            files = data["files"]
            requested_set = set(task.files)
            filtered = [f for f in files if f.get("path", "") in requested_set]

            if not filtered:
                filtered = files

            task.status = "done"
            logger.info(f"[{task.task_id}] [OK] Done in {elapsed:.1f}s -> {len(filtered)} files")
            return filtered
        else:
            logger.error(f"[{task.task_id}] [FAIL] Failed to parse response")
            task.status = "failed"
            return []

    except Exception as e:
        logger.error(f"[{task.task_id}] [FAIL] Error: {e}")
        task.status = "failed"
        return []


