def run_shell(command, cwd, timeout=120):
    """Run a shell command, return (success, stdout+stderr)."""
    import subprocess
    try:
        result = subprocess.run(
            command,
            shell=True,
            cwd=str(cwd),
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        output = result.stdout + "\n" + result.stderr
        return result.returncode == 0, output.strip()
    except subprocess.TimeoutExpired:
        return False, f"TIMEOUT after {timeout}s running: {command}"
    except Exception as e:
        return False, str(e)


