# -- Dependency Resolver ----------------------------------------------------

def get_ready_tasks(tasks):
    """Return tasks whose dependencies are all done."""
    ready = []
    for t in tasks:
        if t.status != "pending":
            continue
        deps_met = all(
            any(other.task_id == dep and other.status == "done" for other in tasks)
            for dep in t.depends_on
        )
        if deps_met:
            ready.append(t)
    return ready


