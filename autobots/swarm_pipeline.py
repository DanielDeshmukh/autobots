def verify_logic(project_path):
    """Basic logic checks: imports resolve, no obvious broken references."""
    issues = []
    src_dir = project_path / "src"
    if not src_dir.exists():
        issues.append("No src/ directory found")
        return issues

    ts_files = list(src_dir.rglob("*.ts")) + list(src_dir.rglob("*.tsx"))
    for f in ts_files:
        rel = f.relative_to(project_path).as_posix()
        content = f.read_text(encoding="utf-8", errors="ignore")
        lines = content.split("\n")
        for i, line in enumerate(lines):
            if "from '" in line or 'from "' in line:
                import_match = line.split("from ")[-1].strip().strip("'\"").rstrip(";")
                if import_match.startswith("./") or import_match.startswith("../"):
                    file_dir = f.parent
                    resolved = (file_dir / import_match).as_posix()
                    candidates = [
                        project_path / f"{resolved}.tsx",
                        project_path / f"{resolved}.ts",
                        project_path / f"{resolved}.jsx",
                        project_path / f"{resolved}.js",
                        project_path / resolved / "index.tsx",
                        project_path / resolved / "index.ts",
                    ]
                    if not any(c.exists() for c in candidates):
                        issues.append(f"{rel}:{i+1} imports '{import_match}' but file not found")
    return issues


