SKILLS_DIR = Path(__file__).parent.parent / "skills"

def load_skills_for_cluster(cluster_name: str, file_extensions: list[str] = None) -> str:
    """Load relevant skills for a cluster based on file types and cluster role."""
    skill_prompts = []
    
    # Map clusters to skill categories
    cluster_skill_map = {
        "Jazz": ["react-components", "tailwind-utils", "css-patterns"],
        "UltraMagnus": ["api-patterns", "state-management", "typescript-patterns"],
        "RedAlert": ["testing-patterns", "security-patterns"],
        "Ratchet": ["debug-patterns", "refactor-patterns"],
        "Perceptor": ["vite-setup", "build-config", "package-management"],
        "Optimus": ["planner-patterns", "architecture-patterns"],
    }
    
    # Get skills for this cluster
    skill_names = cluster_skill_map.get(cluster_name, [])
    
    # Add skills based on file extensions
    if file_extensions:
        for ext in file_extensions:
            if ext in [".tsx", ".jsx"]:
                if "react-components" not in skill_names:
                    skill_names.append("react-components")
            elif ext in [".css", ".scss"]:
                if "tailwind-utils" not in skill_names:
                    skill_names.append("tailwind-utils")
            elif ext in [".ts", ".js"]:
                if "typescript-patterns" not in skill_names:
                    skill_names.append("typescript-patterns")
    
    # Load skill files
    for skill_name in skill_names:
        skill_file = SKILLS_DIR / f"{skill_name}.md"
        if skill_file.exists():
            content = skill_file.read_text(encoding="utf-8")
            skill_prompts.append(f"=== SKILL: {skill_name} ===\n{content}\n=== END SKILL ===")
    
    # Also load any project-specific skills from output directory
    return "\n\n".join(skill_prompts)


def load_project_skills(project_path: Path) -> str:
    """Load skills generated by previous workers in this project."""
    skill_prompts = []
    skills_dir = project_path / ".autobots-skills"
    if skills_dir.exists():
        for skill_file in skills_dir.glob("*.md"):
            content = skill_file.read_text(encoding="utf-8")
            skill_prompts.append(f"=== PROJECT SKILL: {skill_file.stem} ===\n{content}\n=== END SKILL ===")
    return "\n\n".join(skill_prompts)


def create_skill_from_task(task, files: list[dict], project_path: Path):
    """Create a skill file from a successful task for future use."""
    if not files or task.status != "done":
        return
    
    skills_dir = project_path / ".autobots-skills"
    skills_dir.mkdir(exist_ok=True)
    
    # Build file list for skill
    file_list = "\n".join([f'- {f.get("path", "unknown")}' for f in files])
    
    # Create skill content with better structure
    skill_content = f"""---
name: {task.cluster.lower()}-{task.task_id.lower()}
description: Auto-generated skill from {task.cluster} cluster for {task.description[:100]}
nim_model: {task.model_used}
nim_endpoint: https://integrate.api.nvidia.com/v1
---

# {task.cluster} Skill: {task.description}

## Files Generated
{file_list}

## Cluster
{task.cluster}

## Model Used
{task.model_used}

## Pattern
This skill was generated from a successful task execution. Use it as a reference
for similar tasks in the future.

## Usage
When similar tasks appear, reference this skill to maintain consistency.
"""
    
    skill_file = skills_dir / f"{task.cluster.lower()}-{task.task_id.lower()}.md"
    skill_file.write_text(skill_content, encoding="utf-8")
    logger.info(f"[SKILL] Created skill: {skill_file.name}")


